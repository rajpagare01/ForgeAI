import hashlib
from typing import List, Dict, Any, Tuple
from app.domain.models import GraphEdge, RepositoryDependency


class DependencyMapCollector:
    """
    100% deterministic collector and renderer for docs/generated/dependencies.md.
    Extracts module call-graphs, imports, and cross-repository dependencies
    from GraphEdge and RepositoryDependency records with zero LLM involvement.
    """

    def __init__(self, generator_version: str = "v1.0.0"):
        self.generator_version = generator_version

    def collect_and_render(
        self,
        edges: List[GraphEdge],
        cross_repo_deps: List[RepositoryDependency],
        commit_sha: str,
        repo_name: str = "Repository",
    ) -> Tuple[str, str, List[Dict[str, str]]]:
        """
        Returns (content_md, content_hash, citations).
        """
        cited_files = set()

        # 1. Module-level internal graph extraction
        module_links: Dict[Tuple[str, str], int] = {}
        edge_details: List[Dict[str, str]] = []

        sorted_edges = sorted(
            edges,
            key=lambda e: (e.source_symbol, e.target_symbol, e.edge_type, str(e.id))
        )

        for e in sorted_edges:
            src = e.source_symbol
            tgt = e.target_symbol
            etype = e.edge_type

            # Extract module prefix (e.g. package or directory)
            src_mod = src.split(".")[0] if "." in src else (src.split("/")[0] if "/" in src else src)
            tgt_mod = tgt.split(".")[0] if "." in tgt else (tgt.split("/")[0] if "/" in tgt else tgt)

            if src_mod != tgt_mod and src_mod and tgt_mod:
                pair = (src_mod, tgt_mod)
                module_links[pair] = module_links.get(pair, 0) + 1

            edge_fp = getattr(e, "file_path", None)
            if not edge_fp and isinstance(getattr(e, "metadata", None), dict):
                edge_fp = e.metadata.get("file_path")
            if edge_fp:
                cited_files.add(edge_fp)

            edge_details.append({
                "source": src,
                "target": tgt,
                "type": etype,
            })

        # 2. Cross-repo dependencies
        sorted_deps = sorted(
            cross_repo_deps,
            key=lambda d: (
                getattr(d, "target_repository_name", None)
                or (d.metadata.get("target_repository_name") if isinstance(getattr(d, "metadata", None), dict) else None)
                or getattr(d, "target_reference", None)
                or str(getattr(d, "target_repository_id", "")),
                getattr(d, "dependency_type", "") or "",
                str(getattr(d, "id", "")),
            )
        )

        for d in sorted_deps:
            manifest = getattr(d, "manifest_path", None)
            if manifest:
                cited_files.add(manifest)
            meta = getattr(d, "metadata", None)
            if isinstance(meta, dict):
                meta_path = meta.get("manifest_path") or meta.get("file_path")
                if meta_path:
                    cited_files.add(meta_path)
            src_ref = getattr(d, "source_reference", None)
            if isinstance(src_ref, str) and src_ref.strip():
                candidate_path = src_ref.split(":")[0].strip() if ":" in src_ref else src_ref.strip()
                if "/" in candidate_path or "." in candidate_path:
                    cited_files.add(candidate_path)

        citations = [
            {"file_path": fp, "commit_sha": commit_sha}
            for fp in sorted(list(cited_files))
        ]

        # 3. Render Markdown
        lines = [
            f"# Dependency Architecture & Topology — {repo_name}",
            "",
            f"> **Generated by ForgeAI** | Version: `{self.generator_version}` | Commit: `{commit_sha}`",
            "",
            "## 1. Overview & Connectivity",
            f"- **Internal Graph Edges:** {len(edges)} static connections (CALLS, IMPORTS, EXTENDS).",
            f"- **Cross-Repository Dependencies:** {len(sorted_deps)} upstream/downstream services.",
            "",
            "## 2. Module Dependency Graph (Mermaid)",
            "```mermaid",
            "graph TD",
        ]

        sorted_links = sorted(module_links.items(), key=lambda x: (x[0][0], x[0][1]))
        if sorted_links:
            for (src_m, tgt_m), count in sorted_links[:25]:  # Bound Mermaid size for layout clarity
                clean_src = src_m.replace("-", "_").replace(".", "_")
                clean_tgt = tgt_m.replace("-", "_").replace(".", "_")
                lines.append(f"    {clean_src} -->|{count} refs| {clean_tgt}")
        else:
            lines.append("    SingleModule[Core Application Module]")

        lines.extend([
            "```",
            "",
            "## 3. Cross-Repository Distributed Dependencies",
            "| Target Repository | Dependency Type | Scope | Version Spec |",
            "| :--- | :--- | :--- | :--- |",
        ])

        if sorted_deps:
            for d in sorted_deps:
                meta = d.metadata if isinstance(getattr(d, "metadata", None), dict) else {}
                target_name = (
                    getattr(d, "target_repository_name", None)
                    or meta.get("target_repository_name")
                    or getattr(d, "target_reference", None)
                    or getattr(d, "source_reference", None)
                    or str(getattr(d, "target_repository_id", "External Service"))
                )
                dep_type = getattr(d, "dependency_type", "RUNTIME")
                scope = getattr(d, "scope", None) or getattr(d, "confidence", None) or "ORGANIZATION"
                version = (
                    getattr(d, "version_spec", None)
                    or meta.get("version")
                    or getattr(d, "evidence_type", "DISCOVERED")
                )
                lines.append(f"| **{target_name}** | `{dep_type}` | `{scope}` | `{version}` |")
        else:
            lines.append("| No external repository dependencies declared | `STANDALONE` | `INTERNAL` | `N/A` |")

        lines.extend([
            "",
            "## 4. Key Static References",
            "| Source Symbol | Target Reference | Edge Type |",
            "| :--- | :--- | :--- |",
        ])

        if edge_details:
            for ed in edge_details[:30]:  # Top 30 representative edges
                lines.append(f"| `{ed['source']}` | `{ed['target']}` | `{ed['type']}` |")
        else:
            lines.append("| `Core` | `Standard Library` | `IMPORTS` |")

        lines.append("")

        content_md = "\n".join(lines)
        content_hash = hashlib.sha256(content_md.encode("utf-8")).hexdigest()
        return content_md, content_hash, citations
