import hashlib
import re
from typing import List, Dict, Any, Tuple
from app.domain.models import CodeChunk


class ApiReferenceCollector:
    """
    100% deterministic collector and renderer for docs/generated/api.md.
    Extracts HTTP REST routes from Spring Boot and FastAPI controllers with zero LLM involvement.
    """

    def __init__(self, generator_version: str = "v1.0.0"):
        self.generator_version = generator_version

    def collect_and_render(
        self,
        chunks: List[CodeChunk],
        commit_sha: str,
        repo_name: str = "Repository",
    ) -> Tuple[str, str, List[Dict[str, str]]]:
        """
        Returns (content_md, content_hash, citations).
        """
        routes: List[Dict[str, str]] = []
        cited_files = set()

        # Sort chunks deterministically
        sorted_chunks = sorted(
            chunks,
            key=lambda c: (c.file_path or "", c.symbol_name or "", str(c.id))
        )

        for c in sorted_chunks:
            if not c.content or not c.file_path:
                continue

            extracted = self._extract_routes_from_chunk(c)
            if extracted:
                routes.extend(extracted)
                cited_files.add(c.file_path)

        # Deduplicate and sort routes deterministically by (Method, Path, Handler, File)
        unique_routes_map: Dict[Tuple[str, str, str, str], Dict[str, str]] = {}
        for r in routes:
            key = (r["method"], r["path"], r["handler"], r["file_path"])
            if key not in unique_routes_map:
                unique_routes_map[key] = r

        sorted_routes = sorted(
            unique_routes_map.values(),
            key=lambda r: (r["path"], r["method"], r["file_path"], r["handler"])
        )

        citations = [
            {"file_path": fp, "commit_sha": commit_sha}
            for fp in sorted(list(cited_files))
        ]

        # Group by method for statistical breakdown
        method_counts: Dict[str, int] = {}
        for r in sorted_routes:
            m = r["method"]
            method_counts[m] = method_counts.get(m, 0) + 1
        sorted_methods = sorted(method_counts.items(), key=lambda x: x[0])

        lines = [
            f"# REST API Reference — {repo_name}",
            "",
            f"> **Generated by ForgeAI** | Version: `{self.generator_version}` | Commit: `{commit_sha}`",
            "",
            "## 1. Overview & Route Statistics",
            f"Total discovered API endpoints: **{len(sorted_routes)}** across {len(citations)} controller files.",
            "",
            "| HTTP Method | Endpoint Count |",
            "| :--- | :--- |",
        ]

        for method, count in sorted_methods:
            lines.append(f"| `{method}` | {count} |")

        lines.extend([
            "",
            "## 2. Discovered Endpoints Specification",
            "| Method | Route / Path | Handler Method / Symbol | Source File |",
            "| :--- | :--- | :--- | :--- |",
        ])

        if sorted_routes:
            for r in sorted_routes:
                citation = f"[{r['file_path']}@{commit_sha}]"
                lines.append(f"| `{r['method']}` | `{r['path']}` | `{r['handler']}` | {citation} |")
        else:
            lines.append("| `NONE` | `N/A` | No HTTP routes discovered | `N/A` |")

        lines.append("")

        content_md = "\n".join(lines)
        content_hash = hashlib.sha256(content_md.encode("utf-8")).hexdigest()
        return content_md, content_hash, citations

    def _extract_routes_from_chunk(self, chunk: CodeChunk) -> List[Dict[str, str]]:
        content = chunk.content
        fp = chunk.file_path
        results = []

        # 1. Spring Boot Controllers
        if "@RestController" in content or "@Controller" in content or "@RequestMapping" in content:
            class_prefix = ""
            base_match = re.search(r'@RequestMapping\s*\(\s*(?:value\s*=\s*)?["\']([^"\']+)["\']', content)
            if base_match:
                class_prefix = base_match.group(1).rstrip("/")

            spring_methods = [
                ("GET", r'@GetMapping\s*(?:\(\s*(?:value\s*=\s*)?["\']?([^"\')\s]*)["\']?\s*\))?'),
                ("POST", r'@PostMapping\s*(?:\(\s*(?:value\s*=\s*)?["\']?([^"\')\s]*)["\']?\s*\))?'),
                ("PUT", r'@PutMapping\s*(?:\(\s*(?:value\s*=\s*)?["\']?([^"\')\s]*)["\']?\s*\))?'),
                ("DELETE", r'@DeleteMapping\s*(?:\(\s*(?:value\s*=\s*)?["\']?([^"\')\s]*)["\']?\s*\))?'),
                ("PATCH", r'@PatchMapping\s*(?:\(\s*(?:value\s*=\s*)?["\']?([^"\')\s]*)["\']?\s*\))?'),
            ]

            for http_method, pattern in spring_methods:
                for match in re.finditer(pattern, content):
                    sub_path = match.group(1) if match.group(1) else ""
                    sub_path = sub_path.strip("\"'")
                    if not sub_path.startswith("/") and sub_path:
                        sub_path = "/" + sub_path
                    full_path = (class_prefix + sub_path) or "/"
                    if not full_path.startswith("/"):
                        full_path = "/" + full_path

                    # Find nearby method name
                    sub_text = content[match.end():match.end() + 200]
                    method_match = re.search(r'public\s+(?:[\w<>\[\],\s]+)\s+(\w+)\s*\(', sub_text)
                    handler = method_match.group(1) if method_match else (chunk.symbol_name or "handler")

                    results.append({
                        "method": http_method,
                        "path": full_path,
                        "handler": handler,
                        "file_path": fp,
                    })

        # 2. FastAPI Routers
        fastapi_pattern = re.compile(
            r'@(?:router|app)\.(get|post|put|delete|patch)\s*\(\s*["\']([^"\']+)["\']',
            re.IGNORECASE
        )
        for match in fastapi_pattern.finditer(content):
            http_method = match.group(1).upper()
            route_path = match.group(2)
            if not route_path.startswith("/"):
                route_path = "/" + route_path

            sub_text = content[match.end():match.end() + 200]
            func_match = re.search(r'(?:async\s+)?def\s+(\w+)\s*\(', sub_text)
            handler = func_match.group(1) if func_match else (chunk.symbol_name or "endpoint")

            results.append({
                "method": http_method,
                "path": route_path,
                "handler": handler,
                "file_path": fp,
            })

        return results

