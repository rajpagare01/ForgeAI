import hashlib
import os
import re
from typing import List, Dict, Any, Tuple
from app.domain.models import CodeChunk


class OverviewCollector:
    """
    100% deterministic collector and renderer for docs/generated/overview.md.
    Zero LLM involvement; byte-identical output guaranteed for identical input chunks.
    """

    def __init__(self, generator_version: str = "v1.0.0"):
        self.generator_version = generator_version

    def collect_and_render(
        self,
        chunks: List[CodeChunk],
        commit_sha: str,
        repo_name: str = "Repository",
    ) -> Tuple[str, str, List[Dict[str, str]]]:
        """
        Returns (content_md, content_hash, citations).
        citations is a list of {"file_path": ..., "commit_sha": ...}
        """
        short_sha = commit_sha[:7] if len(commit_sha) >= 7 else commit_sha
        file_paths = sorted(list({c.file_path for c in chunks if c.file_path}))
        
        # 1. Tech stack detection
        stacks = self._detect_tech_stacks(chunks, file_paths)
        
        # 2. Module breakdown
        modules = self._detect_modules(file_paths)
        
        # 3. Entry point discovery
        entry_points = self._detect_entry_points(chunks, commit_sha)
        
        # 4. Symbol count summaries
        symbol_counts: Dict[str, int] = {}
        for c in chunks:
            stype = c.symbol_type or "OTHER"
            symbol_counts[stype] = symbol_counts.get(stype, 0) + 1
        sorted_symbols = sorted(symbol_counts.items(), key=lambda x: x[0])

        # 5. Build citations
        cited_files = set()
        for ep in entry_points:
            cited_files.add(ep["file_path"])
        # Also cite top files if empty
        if not cited_files and file_paths:
            cited_files.update(file_paths[:5])
        
        citations = [
            {"file_path": fp, "commit_sha": commit_sha}
            for fp in sorted(list(cited_files))
        ]

        # 6. Render deterministic Markdown
        lines = [
            f"# Repository Overview — {repo_name}",
            "",
            f"> **Generated by ForgeAI** | Version: `{self.generator_version}` | Commit: `{commit_sha}`",
            "",
            "## 1. Executive Summary",
            f"This document provides an automated architectural overview of **{repo_name}** at commit `{short_sha}`. "
            f"It was deterministically generated from {len(file_paths)} indexed source files and {len(chunks)} parsed code chunks.",
            "",
            "## 2. Technology Stack",
            "| Technology / Layer | Detected In | Primary Role |",
            "| :--- | :--- | :--- |",
        ]

        if stacks:
            for s in stacks:
                lines.append(f"| **{s['name']}** | `{s['indicator']}` | {s['role']} |")
        else:
            lines.append("| **Generic Software** | `Source files` | Application source code |")

        lines.extend([
            "",
            "## 3. Directory & Module Structure",
            "| Top-Level Directory | File Count | Purpose / Scope |",
            "| :--- | :--- | :--- |",
        ])

        for mod, count in modules:
            lines.append(f"| `{mod}/` | {count} | Module / component scope |")

        lines.extend([
            "",
            "## 4. Primary Entry Points",
            "| Entry Point / Component | Source File | Type |",
            "| :--- | :--- | :--- |",
        ])

        if entry_points:
            for ep in entry_points:
                citation = f"[{ep['file_path']}@{commit_sha}]"
                lines.append(f"| `{ep['name']}` | {citation} | {ep['type']} |")
        else:
            lines.append(f"| `Repository Root` | `{repo_name}` | Application Root |")

        lines.extend([
            "",
            "## 5. Code Symbol Distribution",
            "| Symbol Category | Count |",
            "| :--- | :--- |",
        ])

        total_symbols = 0
        for stype, scount in sorted_symbols:
            lines.append(f"| {stype} | {scount} |")
            total_symbols += scount
        lines.append(f"| **Total Symbols** | **{total_symbols}** |")
        lines.append("")

        content_md = "\n".join(lines)
        content_hash = hashlib.sha256(content_md.encode("utf-8")).hexdigest()
        return content_md, content_hash, citations

    def _detect_tech_stacks(self, chunks: List[CodeChunk], file_paths: List[str]) -> List[Dict[str, str]]:
        stacks = []
        path_set = set(file_paths)
        has_java = any(fp.endswith(".java") for fp in path_set) or "pom.xml" in path_set
        has_python = any(fp.endswith(".py") for fp in path_set) or "requirements.txt" in path_set or "pyproject.toml" in path_set
        has_ts = any(fp.endswith(".ts") or fp.endswith(".tsx") for fp in path_set) or "package.json" in path_set
        has_sql = any(fp.endswith(".sql") for fp in path_set)
        has_docker = "Dockerfile" in path_set or any("docker-compose" in fp for fp in path_set)

        if has_java:
            stacks.append({"name": "Java / Spring Boot", "indicator": "pom.xml / *.java", "role": "Backend microservice & domain model"})
        if has_python:
            stacks.append({"name": "Python / FastAPI", "indicator": "requirements.txt / *.py", "role": "AI orchestration, static analysis & embeddings"})
        if has_ts:
            stacks.append({"name": "TypeScript / Next.js", "indicator": "package.json / *.tsx", "role": "Interactive governance frontend"})
        if has_sql:
            stacks.append({"name": "PostgreSQL / Flyway", "indicator": "*.sql migrations", "role": "Relational persistence & vector storage"})
        if has_docker:
            stacks.append({"name": "Docker Containerization", "indicator": "Dockerfile / docker-compose.yml", "role": "Service deployment & container orchestration"})

        return stacks

    def _detect_modules(self, file_paths: List[str]) -> List[Tuple[str, int]]:
        dir_counts: Dict[str, int] = {}
        for fp in file_paths:
            parts = fp.replace("\\", "/").split("/")
            if len(parts) > 1:
                top = parts[0]
                if top == "services" and len(parts) > 2:
                    top = f"services/{parts[1]}"
                dir_counts[top] = dir_counts.get(top, 0) + 1
            else:
                dir_counts["root"] = dir_counts.get("root", 0) + 1
        return sorted(dir_counts.items(), key=lambda x: x[0])

    def _detect_entry_points(self, chunks: List[CodeChunk], commit_sha: str) -> List[Dict[str, str]]:
        entry_points = []
        seen = set()

        # Sort chunks deterministically by file_path and symbol_name
        sorted_chunks = sorted(
            chunks,
            key=lambda c: (c.file_path or "", c.symbol_name or "", str(c.id))
        )

        for c in sorted_chunks:
            if not c.content or not c.file_path:
                continue
            key = (c.file_path, c.symbol_name)
            if key in seen:
                continue

            content = c.content
            fp = c.file_path

            if "@SpringBootApplication" in content or "SpringApplication.run" in content:
                seen.add(key)
                entry_points.append({
                    "name": c.symbol_name or os.path.basename(fp),
                    "file_path": fp,
                    "type": "Spring Boot Main Entry Point",
                })
            elif "FastAPI(" in content or "app = FastAPI" in content:
                seen.add(key)
                entry_points.append({
                    "name": c.symbol_name or "FastAPI App",
                    "file_path": fp,
                    "type": "FastAPI Application",
                })
            elif fp.endswith("page.tsx") or fp.endswith("layout.tsx"):
                seen.add(key)
                entry_points.append({
                    "name": os.path.basename(os.path.dirname(fp)) or "Page",
                    "file_path": fp,
                    "type": "Next.js UI Route Component",
                })
            elif re.search(r"def\s+main\s*\(", content) or "if __name__ == '__main__':" in content:
                seen.add(key)
                entry_points.append({
                    "name": "main()",
                    "file_path": fp,
                    "type": "CLI / Script Entry Point",
                })

        return sorted(entry_points, key=lambda x: (x["type"], x["file_path"], x["name"]))

