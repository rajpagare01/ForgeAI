import hashlib
import re
from typing import List, Dict, Any, Tuple
from app.domain.models import CodeChunk


class DataModelCollector:
    """
    100% deterministic collector and renderer for docs/generated/data-model.md.
    Extracts database tables, columns, primary keys, and foreign key relationships
    from SQL migrations and JPA entities, rendering schema specifications and Mermaid ER diagrams.
    """

    def __init__(self, generator_version: str = "v1.0.0"):
        self.generator_version = generator_version

    def collect_and_render(
        self,
        chunks: List[CodeChunk],
        commit_sha: str,
        repo_name: str = "Repository",
    ) -> Tuple[str, str, List[Dict[str, str]]]:
        """
        Returns (content_md, content_hash, citations).
        """
        tables: Dict[str, Dict[str, Any]] = {}
        relationships: List[Dict[str, str]] = []
        cited_files = set()

        # Sort chunks deterministically
        sorted_chunks = sorted(
            chunks,
            key=lambda c: (c.file_path or "", c.symbol_name or "", str(c.id))
        )

        for c in sorted_chunks:
            if not c.content or not c.file_path:
                continue

            fp = c.file_path
            content = c.content

            if fp.endswith(".sql"):
                extracted_tables, extracted_rels = self._parse_sql_ddl(content, fp)
                for tname, tdata in extracted_tables.items():
                    if tname not in tables:
                        tables[tname] = tdata
                    else:
                        tables[tname]["columns"].extend(tdata["columns"])
                    cited_files.add(fp)
                relationships.extend(extracted_rels)

            elif "@Entity" in content or "@Table" in content:
                jpa_table = self._parse_jpa_entity(content, fp, c.symbol_name)
                if jpa_table:
                    tname = jpa_table["name"]
                    if tname not in tables:
                        tables[tname] = jpa_table
                    else:
                        tables[tname]["columns"].extend(jpa_table["columns"])
                    cited_files.add(fp)

            elif (
                (fp.endswith(".py") and ("BaseModel" in content or "__tablename__" in content))
                or ((fp.endswith(".ts") or fp.endswith(".tsx")) and (re.search(r'\binterface\s+[A-Za-z0-9_]+', content) or re.search(r'\btype\s+[A-Za-z0-9_]+\s*=\s*\{', content)))
            ):
                extracted_models = self._parse_python_or_ts_model(content, fp, c.symbol_name)
                for m_table in extracted_models:
                    tname = m_table["name"]
                    if tname not in tables:
                        tables[tname] = m_table
                    else:
                        tables[tname]["columns"].extend(m_table["columns"])
                    cited_files.add(fp)

        # Sort tables and their columns deterministically
        sorted_table_names = sorted(tables.keys())
        for tname in sorted_table_names:
            col_dict = {}
            for col in tables[tname]["columns"]:
                cname = col["name"]
                if cname not in col_dict:
                    col_dict[cname] = col
            tables[tname]["columns"] = [col_dict[c] for c in sorted(col_dict.keys())]

        # Deduplicate relationships and sort
        unique_rels = []
        seen_rels = set()
        for rel in sorted(relationships, key=lambda r: (r["source"], r["target"], r.get("label", ""))):
            key = (rel["source"], rel["target"], rel.get("label", ""))
            if key not in seen_rels:
                seen_rels.add(key)
                unique_rels.append(rel)

        citations = [
            {"file_path": fp, "commit_sha": commit_sha}
            for fp in sorted(list(cited_files))
        ]

        # Render Markdown
        lines = [
            f"# Data Model & Schema Architecture — {repo_name}",
            "",
            f"> **Generated by ForgeAI** | Version: `{self.generator_version}` | Commit: `{commit_sha}`",
            "",
            "## 1. Schema Overview",
            f"Total discovered persistent tables / entities: **{len(sorted_table_names)}** across {len(citations)} schema definitions.",
            "",
            "## 2. Entity-Relationship Diagram (Mermaid)",
            "```mermaid",
            "erDiagram",
        ]

        if sorted_table_names:
            for tname in sorted_table_names:
                cols = tables[tname]["columns"]
                lines.append(f"    {tname} {{")
                for c in cols[:10]:  # Limit diagram fields to prevent Mermaid overload
                    ctype = c["type"].replace(" ", "_").replace("(", "_").replace(")", "")
                    col_marker = "PK" if c.get("is_pk") else ("FK" if c.get("is_fk") else "")
                    lines.append(f"        {ctype} {c['name']} {col_marker}".strip())
                lines.append("    }")

            for rel in unique_rels:
                src = rel["source"]
                tgt = rel["target"]
                label = rel.get("label", "references")
                if src in tables and tgt in tables:
                    lines.append(f"    {src} }}o--|| {tgt} : \"{label}\"")
        else:
            lines.append("    NO_TABLES_FOUND {")
            lines.append("        string placeholder")
            lines.append("    }")

        lines.extend([
            "```",
            "",
            "## 3. Detailed Table Specifications",
        ])

        if sorted_table_names:
            for tname in sorted_table_names:
                tdata = tables[tname]
                citation = f"[{tdata['file_path']}@{commit_sha}]"
                lines.extend([
                    f"### Table `{tname}`",
                    f"- **Source Definition:** {citation}",
                    f"- **Total Columns:** {len(tdata['columns'])}",
                    "",
                    "| Column Name | Data Type | Modifiers / Key |",
                    "| :--- | :--- | :--- |",
                ])
                for col in tdata["columns"]:
                    mod = []
                    if col.get("is_pk"):
                        mod.append("PRIMARY KEY")
                    if col.get("is_fk"):
                        mod.append(f"FK -> {col.get('fk_target', '')}")
                    if col.get("is_unique"):
                        mod.append("UNIQUE")
                    if not col.get("nullable", True):
                        mod.append("NOT NULL")
                    mod_str = ", ".join(mod) if mod else "NULLABLE"
                    lines.append(f"| `{col['name']}` | `{col['type']}` | {mod_str} |")
                lines.append("")
        else:
            lines.append("No SQL DDL or JPA entities discovered in this repository.")
            lines.append("")

        content_md = "\n".join(lines)
        content_hash = hashlib.sha256(content_md.encode("utf-8")).hexdigest()
        return content_md, content_hash, citations

    def _parse_sql_ddl(self, content: str, file_path: str) -> Tuple[Dict[str, Dict[str, Any]], List[Dict[str, str]]]:
        tables = {}
        relationships = []

        # Find CREATE TABLE blocks
        create_table_regex = re.compile(
            r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s*\((.*?)\);',
            re.IGNORECASE | re.DOTALL
        )

        for match in create_table_regex.finditer(content):
            table_name = match.group(1).lower()
            body = match.group(2)
            columns = []

            # Split statements inside parentheses by comma, careful with nested parens
            parts = [p.strip() for p in re.split(r',\s*(?![^()]*\))', body) if p.strip()]
            for part in parts:
                cleaned = " ".join(part.split())
                upper_part = cleaned.upper()
                if upper_part.startswith("CONSTRAINT") or upper_part.startswith("PRIMARY KEY (") or upper_part.startswith("FOREIGN KEY"):
                    # Check for foreign key table reference
                    fk_match = re.search(r'FOREIGN\s+KEY\s*\([^)]+\)\s+REFERENCES\s+([a-zA-Z0-9_]+)', upper_part)
                    if fk_match:
                        target_tbl = fk_match.group(1).lower()
                        relationships.append({"source": table_name, "target": target_tbl, "label": "references"})
                    continue

                col_tokens = cleaned.split()
                if len(col_tokens) >= 2:
                    col_name = col_tokens[0].replace('"', '').replace('`', '').lower()
                    col_type = col_tokens[1].upper()
                    is_pk = "PRIMARY KEY" in upper_part
                    is_unique = "UNIQUE" in upper_part
                    nullable = "NOT NULL" not in upper_part
                    is_fk = "REFERENCES" in upper_part
                    fk_target = ""

                    if is_fk:
                        fk_match = re.search(r'REFERENCES\s+([a-zA-Z0-9_]+)', upper_part)
                        if fk_match:
                            target_tbl = fk_match.group(1).lower()
                            fk_target = target_tbl
                            relationships.append({"source": table_name, "target": target_tbl, "label": "references"})

                    columns.append({
                        "name": col_name,
                        "type": col_type,
                        "is_pk": is_pk,
                        "is_fk": is_fk,
                        "fk_target": fk_target,
                        "is_unique": is_unique,
                        "nullable": nullable,
                    })

            tables[table_name] = {
                "name": table_name,
                "file_path": file_path,
                "columns": columns,
            }

        return tables, relationships

    def _parse_jpa_entity(self, content: str, file_path: str, symbol_name: str | None) -> Dict[str, Any] | None:
        table_name = None
        match = re.search(r'@Table\s*\(\s*name\s*=\s*["\']([^"\']+)["\']', content)
        if match:
            table_name = match.group(1).lower()
        else:
            effective_symbol = symbol_name
            if not effective_symbol:
                cls_match = re.search(r'\bclass\s+([A-Za-z0-9_]+)', content)
                effective_symbol = cls_match.group(1) if cls_match else None
            if effective_symbol:
                table_name = re.sub(r'(?<!^)(?=[A-Z])', '_', effective_symbol).lower()
            else:
                return None

        columns = []
        field_matches = re.finditer(
            r'(?:private|protected)\s+([A-Za-z0-9_<>\[\],\s]+?)\s+([a-zA-Z0-9_]+)\s*(?:=[^;]*)?;',
            content,
            re.DOTALL,
        )
        for fm in field_matches:
            ftype = re.sub(r'\s+', ' ', fm.group(1).strip())
            fname = fm.group(2)
            raw_prefix = content[max(0, fm.start() - 200):fm.start()]
            # Isolate annotations belonging only to this field (after previous ; or {)
            last_delim = max(raw_prefix.rfind(";"), raw_prefix.rfind("{"))
            prefix = raw_prefix[last_delim + 1:] if last_delim != -1 else raw_prefix
            is_pk = "@Id" in prefix
            is_fk = "@ManyToOne" in prefix or "@JoinColumn" in prefix
            not_nullable = bool(re.search(r'nullable\s*=\s*false', prefix))
            columns.append({
                "name": fname,
                "type": ftype,
                "is_pk": is_pk,
                "is_fk": is_fk,
                "nullable": not (is_pk or not_nullable),
            })

        return {
            "name": table_name,
            "file_path": file_path,
            "columns": columns,
        }

    def _parse_python_or_ts_model(
        self, content: str, file_path: str, symbol_name: str | None
    ) -> List[Dict[str, Any]]:
        results: List[Dict[str, Any]] = []
        if file_path.endswith(".py"):
            class_matches = list(re.finditer(r'^class\s+([A-Za-z0-9_]+)\s*(?:\(([^)]*)\))?\s*:', content, re.MULTILINE))
            for idx, cm in enumerate(class_matches):
                cls_name = cm.group(1)
                bases = cm.group(2) or ""
                end_pos = class_matches[idx + 1].start() if idx + 1 < len(class_matches) else len(content)
                body = content[cm.end():end_pos]
                tablename_match = re.search(r'__tablename__\s*=\s*["\']([^"\']+)["\']', body)
                if "BaseModel" not in bases and not tablename_match:
                    continue
                tname = tablename_match.group(1).lower() if tablename_match else re.sub(r'(?<!^)(?=[A-Z])', '_', cls_name).lower()
                columns = []
                # Annotated fields (Pydantic / SQLAlchemy 2.0 Mapped)
                for line in body.splitlines():
                    stripped = line.strip()
                    if not stripped or stripped.startswith("#") or stripped.startswith("def ") or stripped.startswith("async def ") or stripped.startswith("@"):
                        continue
                    # Column(...) style
                    sa_col = re.match(r'^([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(?:mapped_)?[Cc]olumn\(([^)]*)\)', stripped)
                    if sa_col:
                        cname = sa_col.group(1)
                        args = sa_col.group(2)
                        ctype = args.split(",")[0].strip() if args else "Any"
                        columns.append({
                            "name": cname,
                            "type": ctype[:40],
                            "is_pk": "primary_key=True" in args,
                            "is_fk": "ForeignKey" in args,
                            "nullable": "nullable=False" not in args and "primary_key=True" not in args,
                        })
                        continue
                    ann_match = re.match(r'^([a-zA-Z_][a-zA-Z0-9_]*)\s*:\s*([^=#\n]+)', stripped)
                    if ann_match and ann_match.group(1) not in ("model_config", "__tablename__"):
                        cname = ann_match.group(1)
                        ctype = ann_match.group(2).strip()
                        is_opt = ctype.startswith("Optional[") or "| None" in ctype or "None |" in ctype
                        is_pk = cname == "id"
                        is_fk = cname.endswith("_id") and not is_pk
                        columns.append({
                            "name": cname,
                            "type": ctype[:40],
                            "is_pk": is_pk,
                            "is_fk": is_fk,
                            "nullable": is_opt and not is_pk,
                        })
                results.append({"name": tname, "file_path": file_path, "columns": columns})
        elif file_path.endswith(".ts") or file_path.endswith(".tsx"):
            ts_blocks = re.finditer(r'(?:export\s+)?(?:interface|type)\s+([A-Za-z0-9_]+)\s*(?:=\s*)?\{([^}]*)\}', content, re.DOTALL)
            for bm in ts_blocks:
                tname = re.sub(r'(?<!^)(?=[A-Z])', '_', bm.group(1)).lower()
                columns = []
                for line in bm.group(2).splitlines():
                    fm = re.match(r'^\s*([a-zA-Z_][a-zA-Z0-9_]*)(\?)?\s*:\s*([^;\n]+)', line)
                    if fm:
                        cname = fm.group(1)
                        is_opt = fm.group(2) == "?"
                        ctype = fm.group(3).strip().rstrip(";")
                        is_pk = cname == "id"
                        is_fk = cname.endswith("Id") and not is_pk
                        columns.append({
                            "name": cname,
                            "type": ctype[:40],
                            "is_pk": is_pk,
                            "is_fk": is_fk,
                            "nullable": is_opt and not is_pk,
                        })
                results.append({"name": tname, "file_path": file_path, "columns": columns})
        return results

