import hashlib
import re
from typing import List, Dict, Any, Tuple
from app.domain.models import CodeChunk


class DataModelCollector:
    """
    100% deterministic collector and renderer for docs/generated/data-model.md.
    Extracts database tables, columns, primary keys, and foreign key relationships
    from SQL migrations and JPA entities, rendering schema specifications and Mermaid ER diagrams.
    """

    def __init__(self, generator_version: str = "v1.0.0"):
        self.generator_version = generator_version

    def collect_and_render(
        self,
        chunks: List[CodeChunk],
        commit_sha: str,
        repo_name: str = "Repository",
    ) -> Tuple[str, str, List[Dict[str, str]]]:
        """
        Returns (content_md, content_hash, citations).
        """
        tables: Dict[str, Dict[str, Any]] = {}
        relationships: List[Dict[str, str]] = []
        cited_files = set()

        # Sort chunks deterministically
        sorted_chunks = sorted(
            chunks,
            key=lambda c: (c.file_path or "", c.symbol_name or "", str(c.id))
        )

        for c in sorted_chunks:
            if not c.content or not c.file_path:
                continue

            fp = c.file_path
            content = c.content

            if fp.endswith(".sql"):
                extracted_tables, extracted_rels = self._parse_sql_ddl(content, fp)
                for tname, tdata in extracted_tables.items():
                    if tname not in tables:
                        tables[tname] = tdata
                    else:
                        tables[tname]["columns"].extend(tdata["columns"])
                    cited_files.add(fp)
                relationships.extend(extracted_rels)

            elif "@Entity" in content or "@Table" in content:
                jpa_table = self._parse_jpa_entity(content, fp, c.symbol_name)
                if jpa_table:
                    tname = jpa_table["name"]
                    if tname not in tables:
                        tables[tname] = jpa_table
                    cited_files.add(fp)

        # Sort tables and their columns deterministically
        sorted_table_names = sorted(tables.keys())
        for tname in sorted_table_names:
            col_dict = {}
            for col in tables[tname]["columns"]:
                cname = col["name"]
                if cname not in col_dict:
                    col_dict[cname] = col
            tables[tname]["columns"] = [col_dict[c] for c in sorted(col_dict.keys())]

        # Deduplicate relationships and sort
        unique_rels = []
        seen_rels = set()
        for rel in sorted(relationships, key=lambda r: (r["source"], r["target"], r.get("label", ""))):
            key = (rel["source"], rel["target"], rel.get("label", ""))
            if key not in seen_rels:
                seen_rels.add(key)
                unique_rels.append(rel)

        citations = [
            {"file_path": fp, "commit_sha": commit_sha}
            for fp in sorted(list(cited_files))
        ]

        # Render Markdown
        lines = [
            f"# Data Model & Schema Architecture — {repo_name}",
            "",
            f"> **Generated by ForgeAI** | Version: `{self.generator_version}` | Commit: `{commit_sha}`",
            "",
            "## 1. Schema Overview",
            f"Total discovered persistent tables / entities: **{len(sorted_table_names)}** across {len(citations)} schema definitions.",
            "",
            "## 2. Entity-Relationship Diagram (Mermaid)",
            "```mermaid",
            "erDiagram",
        ]

        if sorted_table_names:
            for tname in sorted_table_names:
                cols = tables[tname]["columns"]
                lines.append(f"    {tname} {{")
                for c in cols[:10]:  # Limit diagram fields to prevent Mermaid overload
                    ctype = c["type"].replace(" ", "_").replace("(", "_").replace(")", "")
                    col_marker = "PK" if c.get("is_pk") else ("FK" if c.get("is_fk") else "")
                    lines.append(f"        {ctype} {c['name']} {col_marker}".strip())
                lines.append("    }")

            for rel in unique_rels:
                src = rel["source"]
                tgt = rel["target"]
                label = rel.get("label", "references")
                if src in tables and tgt in tables:
                    lines.append(f"    {src} }}o--|| {tgt} : \"{label}\"")
        else:
            lines.append("    NO_TABLES_FOUND {")
            lines.append("        string placeholder")
            lines.append("    }")

        lines.extend([
            "```",
            "",
            "## 3. Detailed Table Specifications",
        ])

        if sorted_table_names:
            for tname in sorted_table_names:
                tdata = tables[tname]
                citation = f"[{tdata['file_path']}@{commit_sha}]"
                lines.extend([
                    f"### Table `{tname}`",
                    f"- **Source Definition:** {citation}",
                    f"- **Total Columns:** {len(tdata['columns'])}",
                    "",
                    "| Column Name | Data Type | Modifiers / Key |",
                    "| :--- | :--- | :--- |",
                ])
                for col in tdata["columns"]:
                    mod = []
                    if col.get("is_pk"):
                        mod.append("PRIMARY KEY")
                    if col.get("is_fk"):
                        mod.append(f"FK -> {col.get('fk_target', '')}")
                    if col.get("is_unique"):
                        mod.append("UNIQUE")
                    if not col.get("nullable", True):
                        mod.append("NOT NULL")
                    mod_str = ", ".join(mod) if mod else "NULLABLE"
                    lines.append(f"| `{col['name']}` | `{col['type']}` | {mod_str} |")
                lines.append("")
        else:
            lines.append("No SQL DDL or JPA entities discovered in this repository.")
            lines.append("")

        content_md = "\n".join(lines)
        content_hash = hashlib.sha256(content_md.encode("utf-8")).hexdigest()
        return content_md, content_hash, citations

    def _parse_sql_ddl(self, content: str, file_path: str) -> Tuple[Dict[str, Dict[str, Any]], List[Dict[str, str]]]:
        tables = {}
        relationships = []

        # Find CREATE TABLE blocks
        create_table_regex = re.compile(
            r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-zA-Z0-9_]+)\s*\((.*?)\);',
            re.IGNORECASE | re.DOTALL
        )

        for match in create_table_regex.finditer(content):
            table_name = match.group(1).lower()
            body = match.group(2)
            columns = []

            # Split statements inside parentheses by comma, careful with nested parens
            parts = [p.strip() for p in re.split(r',\s*(?![^()]*\))', body) if p.strip()]
            for part in parts:
                cleaned = " ".join(part.split())
                upper_part = cleaned.upper()
                if upper_part.startswith("CONSTRAINT") or upper_part.startswith("PRIMARY KEY (") or upper_part.startswith("FOREIGN KEY"):
                    # Check for foreign key table reference
                    fk_match = re.search(r'FOREIGN\s+KEY\s*\([^)]+\)\s+REFERENCES\s+([a-zA-Z0-9_]+)', upper_part)
                    if fk_match:
                        target_tbl = fk_match.group(1).lower()
                        relationships.append({"source": table_name, "target": target_tbl, "label": "references"})
                    continue

                col_tokens = cleaned.split()
                if len(col_tokens) >= 2:
                    col_name = col_tokens[0].replace('"', '').replace('`', '').lower()
                    col_type = col_tokens[1].upper()
                    is_pk = "PRIMARY KEY" in upper_part
                    is_unique = "UNIQUE" in upper_part
                    nullable = "NOT NULL" not in upper_part
                    is_fk = "REFERENCES" in upper_part
                    fk_target = ""

                    if is_fk:
                        fk_match = re.search(r'REFERENCES\s+([a-zA-Z0-9_]+)', upper_part)
                        if fk_match:
                            target_tbl = fk_match.group(1).lower()
                            fk_target = target_tbl
                            relationships.append({"source": table_name, "target": target_tbl, "label": "references"})

                    columns.append({
                        "name": col_name,
                        "type": col_type,
                        "is_pk": is_pk,
                        "is_fk": is_fk,
                        "fk_target": fk_target,
                        "is_unique": is_unique,
                        "nullable": nullable,
                    })

            tables[table_name] = {
                "name": table_name,
                "file_path": file_path,
                "columns": columns,
            }

        return tables, relationships

    def _parse_jpa_entity(self, content: str, file_path: str, symbol_name: str | None) -> Dict[str, Any] | None:
        table_name = None
        match = re.search(r'@Table\s*\(\s*name\s*=\s*["\']([^"\']+)["\']', content)
        if match:
            table_name = match.group(1).lower()
        elif symbol_name:
            # Fallback to snake_case of class name
            table_name = re.sub(r'(?<!^)(?=[A-Z])', '_', symbol_name).lower()
        else:
            return None

        columns = []
        field_matches = re.finditer(r'(?:@Column\s*\([^)]*\)\s*)?(?:@Id\s+)?(?:private|protected)\s+([A-Za-z0-9_<>]+)\s+([a-zA-Z0-9_]+);', content)
        for fm in field_matches:
            ftype = fm.group(1)
            fname = fm.group(2)
            is_pk = "@Id" in content[max(0, fm.start() - 50):fm.start()]
            columns.append({
                "name": fname,
                "type": ftype,
                "is_pk": is_pk,
                "is_fk": False,
                "nullable": not is_pk,
            })

        return {
            "name": table_name,
            "file_path": file_path,
            "columns": columns,
        }

